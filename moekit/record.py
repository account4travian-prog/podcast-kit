"""RUN-RECORD.md, generated from state.json and the build files.

Every number in the record is computed here. The operator writes only inside
the MEDIATOR NOTES block, which survives regeneration.
"""
import json
import os
import re

from . import lint

NOTES_START = "<!-- MEDIATOR NOTES: write below this line; kept when the record is regenerated -->"
NOTES_END = "<!-- END MEDIATOR NOTES -->"


def build(room):
    s, cfg = room.s, room.cfg
    path = os.path.join(room.path, "RUN-RECORD.md")
    notes = "(none yet)"
    if os.path.exists(path):
        old = open(path, encoding="utf-8").read()
        m = re.search(re.escape(NOTES_START) + r"\n(.*?)\n" + re.escape(NOTES_END), old, re.S)
        if m:
            notes = m.group(1).strip() or notes
    st = lint.room_stats(room.committed())
    ros = cfg["run_of_show"]
    acts = s["actions"]
    first = [a for a in acts if a["kind"] == "watch" and a["attempt"] == 0]
    proposals = [a for a in acts if a["kind"] == "propose" and a["attempt"] == 0]
    objections = [t for t in s["turns"] if "objection" in t["history"]]
    repairs = [a for a in acts if a["attempt"] > 0]
    by_check = {}
    for t in objections:
        c = (t["history"]["objection"].get("CHECK") or "?").strip().lower()
        by_check[c] = by_check.get(c, 0) + 1
    recheck_obj = [t for t in objections if t["history"]["recheck"]["ruling"] == "OBJECT"]
    invalid = [t for t in s["turns"] if (t["history"].get("first_ruling") or {}).get("note")]
    overrides = [t for t in s["turns"] if t.get("lint_override")]
    autofixed = [t for t in s["turns"] if t.get("autofix_removed")]
    fr = [t["n"] for t in s["turns"] if t.get("friction")]
    L = []
    L.append(f"# {cfg['title']} - run record\n")
    L.append(f"Generated by moe-kit from state.json. Room created {s['created']}. Phase: **{s['phase']}**.\n")
    L.append("## Cast")
    for c in cfg["cast"]:
        L.append(f"- {c['full_name']} ({c['role']}) - voice `{c.get('voice') or 'NOT SET'}`; context files: "
                 + ", ".join(os.path.basename(p) for p in c["files"]))
    L.append("\n## Source documents (sha256 at room creation)")
    changed = []
    for p, h in s["sources"].items():
        cur = room_fsha(p)
        flag = "" if cur == h else "  **CHANGED SINCE ROOM CREATED**"
        if flag:
            changed.append(p)
        L.append(f"- `{os.path.basename(p)}` {h[:16]}{flag}")
    L.append("\n## The room")
    L.append(f"- Turns committed: {st['turns']}; spoken words: {st['words']} (budget {ros['word_budget']}, "
             f"hard stop {ros['hard_stop']}); passes: {len(s['passes'])}.")
    L.append(f"- Turns of ten words or fewer: {st['short_turns']} ({int(100 * st['short_share'])}%; target >= 35%). "
             f"Guest median turn: {st['guest_median_words']} words (target 15-25). Contractions per 100 words: "
             f"{st['contractions_per_100w']}.")
    long_guest = [t for t in s["turns"] if t["role"] == "guest" and t["words"] > 50]
    L.append(f"- Guest turns over fifty words: {len(long_guest)}" +
             ("".join(f"\n  - T{t['n']} {t['speaker']} ({t['words']} w): {t.get('reason') or 'NO REASON'}" for t in long_guest)))
    if ros.get("solo_brief"):
        L.append(f"- Solo segment (host only). Brief: {ros['solo_brief']}")
    else:
        L.append(f"- Booked friction (\"{ros['friction']}\"): " + (f"host marked it at T{fr[0]}." if fr else
                 "**did NOT happen** (host never marked it)."))
    for spk, p in st["per_speaker"].items():
        L.append(f"- {spk}: turn lengths {p['words']}; structural shapes {p['shapes'] or 'none'}; delivery cells "
                 f"{p['cells']}; sound marks {p['points']}, directions {p['directions']}.")
    L.append("\n## Watcher statistics")
    L.append(f"- Proposals: {len(proposals)} first proposals + {len(objections)} restatements. First-pass audits: "
             f"{len(first)}; objections: {len(objections)} ({', '.join(f'{k} {v}' for k, v in by_check.items()) or 'none'}).")
    L.append(f"- Re-check objections (recorded, not enforced - no second veto): {len(recheck_obj)}"
             + "".join(f"\n  - T{t['n']}: [{t['history']['recheck']['objection'].get('CHECK')}] "
                       f"\"{(t['history']['recheck']['objection'].get('PHRASE') or '').strip(chr(34))}\"" for t in recheck_obj))
    L.append(f"- Format repairs requested: {len(repairs)}. Watcher replies invalid twice (recorded as PASS): {len(invalid)}. "
             f"Turns committed with a format problem after repair: {len(overrides)}. Turns where the kit stripped "
             f"rule-breaking marks after a failed repair (words unchanged): {len(autofixed)}"
             + "".join(f"\n  - T{t['n']}: removed {' '.join(t['autofix_removed'])}" for t in autofixed))
    copied = [a for a in acts if a.get("copies")]
    if copied:
        later = [a for a in copied if a.get("chosen_copy", 1) > 1]
        L.append(f"- Parallel drafting: {len(copied)} drafting jobs ran {copied[0]['copies']} fresh agents on the same "
                 f"prompt; a later copy was used {len(later)} times (the first failed the code checks). Rule: first copy "
                 "in fixed order that passes the code checks - never a judgment of quality. Unused copies entered no context.")
    pend = [t["n"] for t in s["turns"] if (t["history"].get("recheck") or {}).get("ruling") == "PENDING"]
    if pend:
        L.append(f"- Re-checks still outstanding (side jobs): {', '.join('T' + str(n) for n in pend)}.")
    for t in objections:
        o = t["history"]["objection"]
        L.append(f"  - T{t['n']} {t['speaker']}: [{o.get('CHECK')}] \"{(o.get('PHRASE') or '').strip(chr(34))}\" - {o.get('WHY')}")
    L.append("\n## Audit")
    if s.get("audit"):
        a = s["audit"]
        L.append(f"- {len(a['flags'])} flags." + (f" Unverified phrases left after repair: {a['problems_left']}" if a["problems_left"] else ""))
        for f in a["flags"]:
            L.append(f"  - T{f['turn']}: {f['detail']}" + ("" if f["phrase_verified"] else "  (phrase NOT found verbatim)"))
        if a.get("summary"):
            L.append(f"- Auditor summary: {a['summary']}")
    else:
        L.append("- not run yet.")
    L.append("\n## Render and mix")
    for mode in ("scene", "turn"):
        mp = os.path.join(room.path, f"render-{mode}", "manifest.json")
        if os.path.exists(mp):
            m = json.load(open(mp))
            L.append(f"- Render ({mode} mode, script: {m.get('script')}): {len(m['units'])} units, temperature "
                     f"{m['temperature']}, top_p {m['top_p']}, {m['billed_bytes']} bytes billed; chosen takes: "
                     + ", ".join(f"U{u['unit']}:take{u.get('chosen', 1)}" for u in m["units"]))
    sp = os.path.join(room.path, "turns", "split.json")
    if os.path.exists(sp):
        loose = [u for u in json.load(open(sp))["units"] if u.get("max_frac_error", 0) > 0.12]
        L.append(f"- Scene split: {'all boundaries fit' if not loose else str(len(loose)) + ' unit(s) with a loose fit - listen at those joins'}.")
    mj = os.path.join(room.path, "mix", "mix.json")
    if os.path.exists(mj):
        m = json.load(open(mj))
        L.append(f"- Mix: {m['duration_s']} s; per-speaker gain {m['speaker_gain_db']}; loudness {m['loudness']}; "
                 f"sha256 {m['sha256'][:16]}.")
    pj = os.path.join(room.path, "prosody.json")
    if os.path.exists(pj):
        p = json.load(open(pj))["summary"]
        L.append("- Prosody spreads (diagnostics, not gates; targets: speech-only rate CV >= ~15%, per-turn pitch-range sd >= ~1 st, level range across turns >= ~4 dB):")
        for spk, v in p.items():
            g = lambda k, f: (v.get(k) or {}).get(f)
            L.append(f"  - {spk}: speech-only rate CV {g('wpm_speech_only_across_turns', 'cv_pct')}%; pitch-range sd "
                     f"{g('f0_range_st_per_turn', 'sd')} st; level range across turns {g('level_db_across_turns', 'range')} dB.")
    if changed:
        L.append("\n**WARNING: a source document changed after the room was created - the agents in this room did not "
                 "all see the same version. Say so when delivering.**")
    L.append("\n## Producer verdict\n- (pending - record the producer's words verbatim in PRODUCER-NOTES.md, not here)")
    L.append("\n## Mediator notes")
    L.append(NOTES_START)
    L.append(notes)
    L.append(NOTES_END + "\n")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(L))
    print(f"wrote {path}")


def room_fsha(p):
    import hashlib
    try:
        return hashlib.sha256(open(p, "rb").read()).hexdigest()
    except OSError:
        return None
